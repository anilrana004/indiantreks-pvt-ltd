function scaleTiers(tiers: PricingTier[], economicPrice: number): PricingTier[] {
  const currentEco = tiers.find((t) => t.name === 'Economic')?.price ?? economicPrice;
  if (!currentEco || currentEco === economicPrice) {
    return tiers.map((t) =>
      t.name === 'Economic'
        ? { ...t, price: economicPrice, originalPrice: Math.round(economicPrice * 1.25) }
        : t,
    );
  }
  const ratio = economicPrice / currentEco;
  return tiers.map((t) => ({
    ...t,
    price: Math.round(t.price * ratio),
    originalPrice: t.originalPrice ? Math.round(t.originalPrice * ratio) : Math.round(t.price * ratio * 1.25),
    deposit: Math.max(799, Math.round(t.deposit * ratio)),
  }));
}

export function applyLiveSitePricing(list: Trek[]): Trek[] {
  return list.map((trek) => {
    const meta = LIVE_SITE_META[trek.id];
    if (!meta) return trek;
    return {
      ...trek,
      days: meta.days,
      nights: meta.nights,
      duration: meta.duration ?? `${meta.nights}N/${meta.days}D`,
      ...(meta.startEndPoint ? { startEndPoint: meta.startEndPoint } : {}),
      ...(meta.location ? { location: meta.location } : {}),
      pricing: scaleTiers(trek.pricing, meta.price),
    };
  });
}

